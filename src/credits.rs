//! Attribution text for the icons a project uses.
//!
//! The output groups icons by set and states each set's author and license as
//! the API reports them. Sets that need visible credit are listed first.

use std::collections::BTreeMap;

use crate::api::SetInfo;
use crate::id::IconId;
use crate::license::{classify, Class};

pub fn markdown(icons: &[IconId], sets: &BTreeMap<String, SetInfo>) -> String {
    let mut by_set: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for id in icons {
        let names = by_set.entry(id.prefix.as_str()).or_default();
        if !names.contains(&id.name.as_str()) {
            names.push(id.name.as_str());
        }
    }
    let mut rows: Vec<(Class, &str, &SetInfo, Vec<&str>)> = by_set
        .into_iter()
        .filter_map(|(prefix, names)| {
            let info = sets.get(prefix)?;
            Some((classify(info.license.spdx.as_deref()), prefix, info, names))
        })
        .collect();
    // Attribution and stricter classes first, then by prefix.
    rows.sort_by_key(|(class, prefix, _, _)| (std::cmp::Reverse(*class), *prefix));

    let mut out = String::from("# Icon credits\n\n");
    for (class, prefix, info, names) in rows {
        let set = link(&info.name, None);
        let author = link(&info.author.name, info.author.url.as_deref());
        let license = link(&info.license.title, info.license.url.as_deref());
        out.push_str(&format!("## {set} (`{prefix}`)\n\n"));
        out.push_str(&format!("- Author: {author}\n"));
        out.push_str(&format!("- License: {license}"));
        if let Some(spdx) = &info.license.spdx {
            let spdx: String = spdx
                .chars()
                .filter(|c| !c.is_control() && *c != '`')
                .collect();
            out.push_str(&format!(" (SPDX: `{spdx}`)"));
        }
        out.push('\n');
        out.push_str(&format!("- Class: {} - {}\n", class.label(), class.note()));
        let list: Vec<String> = names.iter().map(|n| format!("`{prefix}:{n}`")).collect();
        out.push_str(&format!("- Icons: {}\n\n", list.join(", ")));
    }
    out.push_str("Generated by iconhunt from the Iconify API. License classes are a reading aid, not legal advice.\n");
    out
}

fn link(text: &str, url: Option<&str>) -> String {
    let text: String = text
        .chars()
        .map(|c| if c.is_control() { ' ' } else { c })
        .collect();
    // Escape what Markdown would read as links or raw HTML.
    let text = text
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('[', "\\[")
        .replace(']', "\\]");
    match url {
        Some(u)
            if (u.starts_with("https://") || u.starts_with("http://"))
                && !u.chars().any(char::is_control) =>
        {
            let url = u
                .replace(' ', "%20")
                .replace('(', "%28")
                .replace(')', "%29")
                .replace('<', "%3C")
                .replace('>', "%3E");
            format!("[{text}]({url})")
        }
        _ => text,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::api::{Author, License};

    fn info(name: &str, spdx: &str) -> SetInfo {
        SetInfo {
            name: name.into(),
            author: Author {
                name: format!("{name} authors"),
                url: Some("https://example.test/a".into()),
            },
            license: License {
                title: spdx.into(),
                spdx: Some(spdx.into()),
                url: Some("https://example.test/l".into()),
            },
            ..SetInfo::default()
        }
    }

    #[test]
    fn groups_by_set_and_puts_attribution_first() {
        let mut sets = BTreeMap::new();
        sets.insert("aaa".to_string(), info("Alpha", "MIT"));
        sets.insert("zzz".to_string(), info("Zeta", "CC-BY-4.0"));
        let icons: Vec<IconId> = ["aaa:home", "zzz:star", "aaa:cog", "aaa:home"]
            .iter()
            .map(|s| IconId::parse(s).unwrap())
            .collect();
        let md = markdown(&icons, &sets);
        let zeta = md.find("## Zeta").unwrap();
        let alpha = md.find("## Alpha").unwrap();
        assert!(zeta < alpha, "{md}");
        assert!(md.contains("- Icons: `aaa:home`, `aaa:cog`\n"));
        assert!(md.contains("- Class: attribution - Credit the author"));
        assert!(md.contains("[Zeta authors](https://example.test/a)"));
    }

    #[test]
    fn api_text_cannot_break_out_of_markdown() {
        let mut sets = BTreeMap::new();
        let mut evil = info("Evil\n# Injected", "MIT");
        evil.license.spdx = Some("MIT`\n\x1b[2J# Owned".into());
        sets.insert("evil".to_string(), evil);
        let md = markdown(&[IconId::parse("evil:x").unwrap()], &sets);
        assert!(!md.contains('\x1b'), "{md}");
        assert!(!md.contains("\n# Injected"), "{md}");
        assert!(!md.contains("\n# Owned"), "{md}");
        assert!(
            md.contains("(SPDX: `MIT [2J# Owned`)") || md.contains("(SPDX: `MIT[2J# Owned`)"),
            "{md}"
        );
    }

    #[test]
    fn raw_html_is_escaped() {
        assert_eq!(
            link("<img src=x onerror=alert(1)>", Some("https://e.test/<x>")),
            "[&lt;img src=x onerror=alert(1)&gt;](https://e.test/%3Cx%3E)"
        );
    }

    #[test]
    fn links_only_web_urls() {
        assert_eq!(link("a]b", Some("javascript:alert(1)")), "a\\]b");
        assert_eq!(link("a\x1b[31m", None), "a \\[31m");
        assert_eq!(
            link("x", Some("https://e.test/a b)")),
            "[x](https://e.test/a%20b%29)"
        );
    }
}
